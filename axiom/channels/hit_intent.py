"""Кто написал сообщение: КЛИЕНТ (ищет услугу) или ИСПОЛНИТЕЛЬ (предлагает её).

ЗАЧЕМ. Слушатель ловит сообщения по ключам ниши, но одно и то же слово стоит и в
запросе, и в рекламе. «Нужен сайт» пишет и заказчик, и веб-студия («нужен сайт? —
обращайтесь»). На живой базе это дало 215 находок, где почти все — объявления
исполнителей, постящих одно и то же по кругу: заказчик в такой ленте теряется.

КАК. Два прохода, дешёвый первым:

  1. ПРАВИЛА — по маркерам в тексте. Бесплатно, мгновенно, ловит подавляющее
     большинство: реклама почти всегда содержит «создаю», «мои услуги», «портфолио»,
     прайс, контакты для связи; запрос — «ищу», «посоветуйте», «кто может».
  2. МОДЕЛЬ — только для того, что правила не разобрали. Одно короткое обращение
     на сообщение, на дешёвой модели это доли копейки.

Порядок важен: сначала ищем маркеры ПРЕДЛОЖЕНИЯ. Рекламный пост часто начинается с
вопроса-крючка («Нужен сайт?»), и проверка спроса первой записала бы его в клиенты.

Результат кладётся в chat_hits.intent: client | vendor | unknown.
"""
from __future__ import annotations

import re

CLIENT = "client"     # ищет исполнителя — наш лид
VENDOR = "vendor"     # предлагает услуги — конкурент
UNKNOWN = "unknown"   # не разобрали

# --------------------------------------------------------------------------- #
#  Маркеры ПРЕДЛОЖЕНИЯ услуг (реклама исполнителя)                             #
# --------------------------------------------------------------------------- #
# Проверяются первыми: рекламный пост нередко открывается вопросом «Нужен сайт?»,
# и без этого приоритета такой текст ушёл бы в клиенты.
_VENDOR = [
    # прямое «я делаю» (в т.ч. от первого лица ед. числа: «занимаюсь», «специализируюсь»)
    r"\b(создаю|делаю|разрабатыва[юе]\w*|пишу|верста[юе]\w*|настраива[юе]\w*|продвига[юе]\w*)\b",
    r"\bзанима[юе]\w*с[ья]\b", r"\bспециализиру[юе]\w*с[ья]\b", r"\bработа[юе]\w* с\b",
    r"\b(изготовл|оказыва[юе]|предоставля[юе]|выполня[юе])\w*\b",
    r"\bчем могу быть полезн\w*\b", r"\bмо[йи] (компани|канал|проект|бот|сервис)\w*\b",
    # предложение и призыв
    r"\bмои услуги\b", r"\bнаши услуги\b", r"\bуслуги\s*[:—-]", r"\bпрайс\b",
    r"\bпортфолио\b", r"\bкейс[ыа]?\b", r"\bрезюме\b",
    r"\bобраща[йи]тесь\b", r"\bпишите в (лс|личку|директ)\b", r"\bжду в лс\b",
    r"\bпо всем вопросам\b", r"\bконсультация бесплатн\w*\b",
    r"\bот \d+\s*(руб|₽|\$|тыс)", r"\bцена от\b", r"\bстоимость от\b",
    r"\bпробн\w+ период\b", r"\bтариф\w*\b",
    # обещание результата клиенту — язык продающего, не покупающего
    r"\b(получа[ей]те|получишь|дад[иеё]м|обеспеч\w+|привед[её]м|увелич\w+)\b.{0,30}"
    r"\b(клиент|заявк|лид|продаж|прибыл|трафик)\w*",
    r"\bпоток\w*\s+(клиент|заявок|лидов)\w*\b", r"\bбез (вложений|рекламы|найма)\b",
    # самопрезентация
    r"\bменя зовут\b.{0,40}\b(я|мы)\b", r"\bя\s+—?\s*(веб|дизайн|разработ|маркетолог|таргет|смм|копирайт)",
    r"\bопыт (работы|более|свыше)\b", r"\b\d+\s*(лет|года?) (опыта|в сфере|на рынке)\b",
    # рекламные хэштеги и оформление
    r"#(помогу|услуги|фриланс|работа|реклама|сотрудничество|вакансия|сайты)",
    r"\b(подпис|переход)\w*\s+(на|в)\s+(канал|телеграм)",
]

# --------------------------------------------------------------------------- #
#  Маркеры СПРОСА (человек ищет исполнителя)                                   #
# --------------------------------------------------------------------------- #
_CLIENT = [
    r"\b(ищу|ищем|нужен|нужна|нужно|нужны|требуется|требуются)\b",
    r"\b(посоветуйте|подскажите|порекоменду[йе]те|кто может|кто дела[ел]|кто возьм[её]тся)\b",
    r"\b(хочу|хотим|планиру[юе]м|собира[юе]мся)\s+(заказать|сделать|запустить|создать|внедрить)\b",
    r"\bгде (найти|заказать|купить)\b", r"\bк кому обратиться\b",
    r"\bесть ли (кто|специалист|мастер)\b", r"\bпомогите найти\b",
    r"\bсколько (стоит|будет стоить|обойд[её]тся)\b",
    r"\bготов (оплатить|заплатить|обсудить бюджет)\b", r"\bбюджет\b.{0,20}\b(есть|до|от)\b",
    r"\b(в поиске|в поисках)\b",
]

# --------------------------------------------------------------------------- #
#  Шум: тексты, которые вообще не про сделку                                   #
# --------------------------------------------------------------------------- #
# Вакансии, анонсы мероприятий, обучающий контент и новости. Слова спроса в них
# встречаются постоянно («ищем в штат», «нужен каждому предпринимателю»), из-за
# чего они лезли в клиентов. Для нас это не лид — оператору такое показывать не за чем.
_NOISE = [
    # вакансия
    (r"\b(ищ[еуя]м|требуется|нужен|нужна)\b.{0,40}\b(в штат|в команду|в офис|на удал[её]нк)\w*",
     "вакансия"),
    (r"\b(вакансия|резюме присылайте|оклад|зарплата|з/п|график работы|полная занятость)\b",
     "вакансия"),
    (r"\bосновные требования\b|\bтребования\s*:", "вакансия"),
    # анонс мероприятия
    (r"\b(анонс|вебинар|мастер-класс|конференц\w+|митап|стендап|интенсив)\b", "анонс"),
    (r"\bsold\s*out\b|\bмест больше нет\b|\bрегистрация (по ссылке|открыта)\b", "анонс"),
    (r"\b\d{1,2}\s+(январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)\w*\s+в\s+\w+",
     "анонс"),
    # обучающий контент / новости
    (r"\b(мини-урок|разбор|дайджест|подборка|чек-лист|инструкция|гайд)\b", "контент"),
    (r"\b(верховный суд|правительство|минэконом|госдума|закон\w* вступ)\w*\b", "новость"),
    (r"\b(следите за|в следующем посте|продолжение в канале)\b", "контент"),
]

# СЛАБЫЕ вендорские маркеры: встречаются у обеих сторон сделки. «Нужен сайт под ключ,
# бюджет обсудим» пишет заказчик ровно теми же словами, что и студия в рекламе. Держим
# их отдельно и НЕ даём перевесить явный спрос — иначе живой запрос уходит в конкуренты
# (реальный случай: «Коллеги, посоветуйте, кто делал сайт под ключ?» → vendor).
_VENDOR_WEAK = [
    r"\bпод ключ\b", r"\bбесплатно\b", r"\bгарантия\b", r"\bскидк\w+\b", r"\bакция\b",
    r"\bсотрудничеств\w+\b", r"\bбюджет\b",
]

_VENDOR_RE = [re.compile(p, re.I) for p in _VENDOR]
_VENDOR_WEAK_RE = [re.compile(p, re.I) for p in _VENDOR_WEAK]
_CLIENT_RE = [re.compile(p, re.I) for p in _CLIENT]
_NOISE_RE = [(re.compile(p, re.I), tag) for p, tag in _NOISE]

# Ссылка/телефон/@ник в тексте — почти всегда контакты для связи в рекламе.
_CONTACTS_RE = re.compile(r"(https?://|t\.me/|@[a-z0-9_]{4,}|\+7\d{10}|8\d{10})", re.I)
# Эмодзи в начале строки — «продающая» вёрстка объявления.
_SELLING_LAYOUT_RE = re.compile(r"^\s*[⭐✅🔥💎👉▪️🚀💰📣🎯🖼🖌🧠‼️❗️➡️✔️]", re.M)
# Маркированный список услуг: несколько строк, начинающихся с «-» или «•».
_BULLET_LIST_RE = re.compile(r"^\s*[-–—•]\s+\S", re.M)


def _looks_like_ad(t: str) -> bool:
    """Рекламный пост опознаётся по форме, даже когда слова нейтральны.

    Заказчик пишет коротко и своими словами («ищу того, кто сделает лендинг»).
    Объявление — это вёрстка: эмодзи-заголовок, перечень услуг, контакты, цены.
    Считаем такие признаки; двух достаточно, чтобы не пускать пост к клиентам.
    """
    signals = 0
    if len(_SELLING_LAYOUT_RE.findall(t)) >= 2:   # эмодзи-заголовки списком
        signals += 1
    if len(_BULLET_LIST_RE.findall(t)) >= 3:      # перечень пунктов
        signals += 1
    if _CONTACTS_RE.search(t):                    # куда писать
        signals += 1
    if len(t) > 400:                              # объявления многословны
        signals += 1
    if re.search(r"[«\"']?\s*(цена|стоимость|тариф|прайс)\w*\s*[:—-]", t, re.I):
        signals += 1
    return signals >= 2


def by_rules(text: str) -> tuple[str, str]:
    """Быстрая классификация по маркерам. Возвращает (намерение, причина).

    Причину сохраняем и показываем оператору: он должен понимать, ПОЧЕМУ находка
    попала в ту или иную корзину, иначе фильтру нельзя доверять.
    """
    t = (text or "").strip()
    if not t:
        return UNKNOWN, "пустой текст"

    # Шум проверяем первым: вакансия и анонс полны слов спроса, но лидом не являются.
    for rx, tag in _NOISE_RE:
        if rx.search(t):
            return VENDOR, tag

    vendor_hits = [r.pattern for r in _VENDOR_RE if r.search(t)]
    client_hits = [r.pattern for r in _CLIENT_RE if r.search(t)]
    weak_hits = [r.pattern for r in _VENDOR_WEAK_RE if r.search(t)]
    ad_form = _looks_like_ad(t)

    # Явный спрос + только слабые вендорские слова («под ключ», «бюджет», «гарантия»)
    # — это заказчик, который описывает желаемое, а не студия, которая продаёт.
    if client_hits and not vendor_hits and weak_hits and not ad_form:
        return CLIENT, f"ищет исполнителя ({len(client_hits)} призн.)"
    if not vendor_hits and weak_hits and not client_hits and ad_form:
        return VENDOR, "рекламный пост (по оформлению)"

    if vendor_hits and not client_hits:
        return VENDOR, f"предлагает услуги ({len(vendor_hits)} призн.)"
    if client_hits and not vendor_hits:
        # Свёрстанное объявление, где спрос — только крючок («Нужен сайт?»).
        # Живой заказчик так не пишет, поэтому форма перевешивает слова.
        if ad_form:
            return VENDOR, "объявление с вопросом-крючком"
        return CLIENT, f"ищет исполнителя ({len(client_hits)} призн.)"
    if vendor_hits and client_hits:
        # Оба набора сразу — почти всегда реклама («Нужен сайт? Создаю сайты»).
        # Клиентом признаём, только если спроса заметно больше и это не объявление.
        if ad_form or len(vendor_hits) >= len(client_hits):
            return VENDOR, "реклама с вопросом-крючком"
        return CLIENT, "запрос с упоминанием услуг"
    if ad_form:
        return VENDOR, "рекламный пост (по оформлению)"
    return UNKNOWN, "явных признаков нет"


_LLM_SYSTEM = (
    "Ты фильтр лидов. По сообщению из Telegram-чата определи, кто его написал:\n"
    "• client — человек ИЩЕТ исполнителя/услугу/подрядчика (потенциальный заказчик);\n"
    "• vendor — человек ПРЕДЛАГАЕТ свои услуги, рекламирует себя или компанию;\n"
    "• unknown — из текста непонятно.\n"
    "Отвечай только по тексту, не додумывай. Реклама часто начинается с вопроса "
    "(«Нужен сайт?») — это всё равно vendor."
)


def by_model(text: str, model: str | None = None) -> tuple[str, str]:
    """Классификация моделью — для того, что не разобрали правила.

    Дешёвая модель (config.MODEL) справляется: задача простая, ответ в одно слово.
    Любой сбой — UNKNOWN, находку не теряем: пусть лучше оператор посмотрит сам,
    чем мы молча выбросим живой запрос из-за подвисшей сети.
    """
    t = (text or "").strip()
    if not t:
        return UNKNOWN, "пустой текст"
    try:
        import config
        from agent import llm
        from pydantic import BaseModel, Field

        class Verdict(BaseModel):
            intent: str = Field(description="client, vendor или unknown")
            why: str = Field(description="краткая причина, до 8 слов, по-русски")

        v = llm.structured(
            model or config.MODEL, _LLM_SYSTEM,
            [{"role": "user", "content": t[:1500]}],
            output_format=Verdict, max_tokens=120, timeout=25,
        )
        intent = (v.intent or "").strip().lower()
        if intent not in (CLIENT, VENDOR, UNKNOWN):
            return UNKNOWN, f"модель ответила «{intent}»"
        return intent, (v.why or "").strip()[:120]
    except Exception as e:  # noqa: BLE001 — фильтр не должен ронять слушатель
        return UNKNOWN, f"модель недоступна: {type(e).__name__}"


def classify(text: str, use_model: bool = True) -> tuple[str, str]:
    """Полная классификация: правила, затем модель для спорного.

    use_model=False — только правила (для массового пересчёта старых находок и
    для случаев, когда LLM-ключа нет).
    """
    intent, why = by_rules(text)
    if intent != UNKNOWN or not use_model:
        return intent, why
    return by_model(text)


