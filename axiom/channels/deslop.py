"""Убирает «нейрослоп» из исходящих: то, что сразу выдаёт текст, написанный моделью.

Зачем. Промпт агента прямо запрещает длинное тире, но Haiku всё равно его ставит:
промпты кампаний сами написаны через «—», и модель копирует их манеру. 25.09.2026
разбор переписок ГГКрым: «Всё просто — проект даёт возможность…», «делает всё —
сажает, ухаживает, собирает», «коллеги по крымской теме 🙂». Живой человек с
телефона так не пишет: длинное тире на клавиатуре не набрать, «ё» почти никто не
ставит, смайл-эмодзи в конце каждой фразы читается шаблоном.

Поэтому правим детерминированно, на последнем шаге перед Telegram (_send_parts) и
при записи исходящего в книжку, чтобы в «Диалогах» было видно ровно то, что ушло.
Смысл текста не трогаем: только знаки и буквы, которые палят автоматику.
"""
from __future__ import annotations

import random
import re

_DASH_BETWEEN = re.compile(r"[ \t]+[—–][ \t]+")      # «слово — слово»
_DASH_LEAD = re.compile(r"(^|\n)[ \t]*[—–][ \t]*")   # «— реплика» в начале строки
_DASH_AFTER_PUNCT = re.compile(r"([.,!?:;)])[ \t]*[—–][ \t]*")  # «Правда?— да»
_DASH_REST = re.compile(r"[—–]")                     # «1—2», «слово—слово»
_SMILE = re.compile(r"[ \t]*(?:🙂|😊|☺️|☺)")
_PUNCT_COMMA = re.compile(r"([.,!?:;])[ \t]*,")      # «?,» после замены тире
_SPACES = re.compile(r"[ \t]{2,}")
_LINE_END_BARE = re.compile(r"(?<=[^\s.,!?:;)])[ \t]*\n")  # строка без знака в конце
_NEWLINES = re.compile(r"[ \t]*\n+[ \t]*")


def clean(text: str | None) -> str:
    """Одно исходящее сообщение → то же сообщение без маркеров «написала модель».

    • « — » между словами → запятая, тире в начале строки убираем, «1—2» → «1-2»;
    • «ё» → «е» (с телефона её почти не ставят);
    • 🙂/😊 → «)» — так пишут в личке живые люди;
    • перенос строки внутри ОДНОГО сообщения → пробел: абзацы в личке выдают
      рассылку, а отдельная мысль должна уходить отдельным сообщением. Строка без
      знака в конце получает точку, иначе две мысли склеятся без границы."""
    if not text:
        return text or ""
    s = _DASH_LEAD.sub(r"\1", text.strip())
    s = _DASH_AFTER_PUNCT.sub(r"\1 ", s)
    s = _DASH_BETWEEN.sub(", ", s)
    s = _DASH_REST.sub("-", s)
    s = _PUNCT_COMMA.sub(r"\1", s)
    s = s.replace("ё", "е").replace("Ё", "Е")
    s = _SMILE.sub(")", s)
    s = _LINE_END_BARE.sub(".\n", s)
    s = _NEWLINES.sub(" ", s)
    s = _SPACES.sub(" ", s)
    return s.strip()


def spin(text: str) -> str:
    """{вариант1|вариант2} → случайный вариант (тот же синтаксис, что в шаблонах
    кампаний). {name}/{spec} без «|» не трогаем — их подставляют дальше."""
    return re.sub(r"\{([^{}|]*\|[^{}]*)\}",
                  lambda m: random.choice(m.group(1).split("|")), text or "")


# Последний дожим: уходит ТОЛЬКО тому, кто прочитал предыдущее и промолчал
# (правило Василия, 25.09.2026: «прочитал и не ответил — можно дожать ещё раз»).
# Не прочитал — не дожимаем: второй непрочитанный пинг копит спам-жалобы, а
# человек его всё равно не увидит. Честный выход («больше не потревожу») снимает
# раздражение и заметно чаще получает ответ, чем очередное напоминание об оффере.
LAST_NUDGE = [
    "{name}, {если сейчас не актуально|если тема не ваша}, просто {скажите|напишите}, {больше не потревожу|не буду больше отвлекать})",
    "{name}, {не буду настаивать|не хочу быть навязчивым}) {если все-таки интересно|если тема откликается}, напишите, {я на связи|расскажу подробнее}",
    "{name}, {последний раз напомню о себе|напомню о себе последний раз}) {если интересно|если актуально}, {напишите|дайте знать}, если нет, тоже {скажите|напишите}, {не потревожу|больше не буду писать}",
]


def last_nudge(name: str) -> str:
    """Готовый текст последнего дожима с обращением по имени (или без него)."""
    text = spin(random.choice(LAST_NUDGE))
    first = (name or "").strip().split(" ")[0] if name else ""
    if first and first[0].isalpha():
        return text.replace("{name}", first)
    return text.replace("{name}, ", "")[:1].upper() + text.replace("{name}, ", "")[1:]
