LABEL = {CLIENT: "клиент", VENDOR: "конкурент", UNKNOWN: "не понятно"}

# Режимы охоты для ниши: что складывать в «Запросы»
HUNT_CLIENTS = "clients"   # только клиенты (по умолчанию — основной сценарий)
HUNT_VENDORS = "vendors"   # только исполнители (изучать рынок / продавать им)
HUNT_ALL = "all"           # всё подряд


def wanted(intent: str, mode: str) -> bool:
    """Нужна ли находка с таким намерением при выбранном режиме охоты.

    UNKNOWN пропускаем всегда, кроме режима «только конкуренты»: неразобранное
    чаще оказывается живым запросом, и терять его дороже, чем показать лишнее.
    """
    if mode == HUNT_ALL:
        return True
    if mode == HUNT_VENDORS:
        return intent == VENDOR
    return intent in (CLIENT, UNKNOWN)
