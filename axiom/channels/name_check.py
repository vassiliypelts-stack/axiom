"""Сверка: тот ли человек за @ником, что записан в карточке.

ЗАЧЕМ. Ники приходят выгрузкой со стороннего сайта, и там имя с ником разъезжаются:
в карточке «Дмитрий Иванович Норка», а ник — @Anna_Dobrokhodskaya. Отправка резолвит
получателя ПО НИКУ (telegram._resolve_entity: username в приоритете), поэтому письмо
уходит другому человеку с обращением «Дмитрий Иванович, добрый день!». Ни один отчёт
этого не показывал: в статистике «отправлено», в переписке — вежливый диалог не с тем.

На живой базе 26.08 так ушло 20 из 22 сообщений — ни один контакт не был пробит
(tg_user_id пуст у всех 613 импортированных), и минимум у пяти ник явно чужой:
женские ники на мужских именах и наоборот.

КАК СВЕРЯЕМ. Строгое сравнение строк тут не работает: человек в TG подписан
«Дима», «Dmitry N.», «Норка | Продажи» — это всё он. Поэтому три уровня, от
надёжного к слабому:

  1. совпало имя или фамилия (нормализованно, с учётом транслита) → ok;
  2. надёжно определился РАЗНЫЙ пол (Дмитрий vs Anna) → mismatch, это и есть
     тот случай, что ловим;
  3. всё остальное → unknown. Не «плохо», а «не смогли решить»: подписан
     «Эксперт по продажам» — сверить нечем, и обвинять не за что.

Модуль ничего не чинит сам и никого не блокирует — только ставит метку. Решение
(писать / не писать / поправить карточку) остаётся за оператором: автоматически
удалять контакт по догадке нельзя, цена ошибки — потерянный лид.
"""
from __future__ import annotations

from channels import fio

# Транслит для сравнения «Dmitry» ↔ «Дмитрий». Не для красоты — только чтобы
# латиница и кириллица сходились в одну строку при сравнении.
_TRANSLIT = {
    "a": "а", "b": "б", "v": "в", "g": "г", "d": "д", "e": "е", "z": "з",
    "i": "и", "y": "й", "k": "к", "l": "л", "m": "м", "n": "н", "o": "о",
    "p": "п", "r": "р", "s": "с", "t": "т", "u": "у", "f": "ф", "h": "х",
    "c": "ц", "w": "в", "j": "ж", "x": "кс", "q": "к",
}
# Пары, которые латиницей пишут по-разному, а звучат одинаково.
_DIGRAPHS = [("sch", "щ"), ("sh", "ш"), ("ch", "ч"), ("zh", "ж"), ("ya", "я"),
             ("yu", "ю"), ("yo", "ё"), ("kh", "х"), ("ts", "ц"), ("ph", "ф"),
             # «-ia»/«-iya» на конце — это «-ия»: Ksenia→ксения, Mariya→мария.
             # Без этого «Ксения» и «Ksenia» не сходились и давали ложный unknown.
             ("iya", "ия"), ("ia", "ия"), ("ee", "и"), ("iy", "и"), ("ij", "и"),
             ("ii", "и")]


def _norm(word: str) -> str:
    """Слово → сравнимая форма: нижний регистр, латиница в кириллицу, ё→е.

    Хвостовые «й/ь/ъ» срезаем: «Дмитрий» и «Dmitri» должны сойтись, а разница в
    последней букве для сверки личности значения не имеет.
    """
    w = (word or "").strip().lower().replace("ё", "е")
    if not w:
        return ""
    if any("a" <= ch <= "z" for ch in w):
        for lat, cyr in _DIGRAPHS:
            w = w.replace(lat, cyr)
        w = "".join(_TRANSLIT.get(ch, ch) for ch in w)
    return w.rstrip("йьъ")


def _tokens(raw: str | None) -> list[str]:
    """Значимые слова имени: без эмодзи, пунктуации и хвостов вида «| Продажи»."""
    out: list[str] = []
    buf = ""
    for ch in (raw or ""):
        if ch.isalpha():
            buf += ch
        else:
            if len(buf) > 1:
                out.append(buf)
            buf = ""
    if len(buf) > 1:
        out.append(buf)
    return out


def compare(crm_name: str | None, tg_name: str | None) -> tuple[str, str]:
    """(вердикт, пояснение). Вердикт: ok | mismatch | unknown.

    crm_name — что записано в карточке, tg_name — как человек подписан в Telegram.
    """
    crm_t = [_norm(t) for t in _tokens(crm_name) if _norm(t)]
    tg_t = [_norm(t) for t in _tokens(tg_name) if _norm(t)]
    if not crm_t or not tg_t:
        return "unknown", "нечего сравнивать (пустое имя)"

    # 1) Прямое совпадение любого значимого слова — самый надёжный признак.
    #    Хватает одного: в TG человек часто оставляет только имя или только фамилию.
    common = set(crm_t) & set(tg_t)
    if common:
        return "ok", f"совпало: {', '.join(sorted(common))}"

    # 2) Совпадение по началу слова — «Дмитрий» ↔ «Дима» так не поймается, но
    #    «Александр» ↔ «Александра», «Евген» ↔ «Евгений» — да. Порог 5 букв, чтобы
    #    не склеивать разных людей по коротким совпадениям («Ана» ↔ «Анатолий»).
    for a in crm_t:
        for b in tg_t:
            n = min(len(a), len(b))
            if n >= 4 and (a.startswith(b[:n]) or b.startswith(a[:n])):
                return "ok", f"совпало начало: {a} ≈ {b}"

    # 3) Разный пол — то самое расхождение, ради которого всё затевалось.
    #    Берём ТОЛЬКО уверенно определённый пол (fio._confident_gender), иначе
    #    ловили бы ложные срабатывания на фамилиях и никах-словах.
    crm_g = _gender(crm_name)
    tg_g = _gender(tg_name)
    if crm_g and tg_g and crm_g != tg_g:
        ru = {"male": "мужчина", "female": "женщина"}
        return "mismatch", (f"в карточке {ru[crm_g]}, в Telegram {ru[tg_g]}")

    return "unknown", "имена разные, но однозначно судить нельзя"


def _gender(raw: str | None) -> str | None:
    """Пол по имени/отчеству — только когда уверены. Иначе None ("male"/"female").

    Латиницу прогоняем через _norm: fio._confident_gender работает по кириллическим
    справочникам и на «Anna» вернул бы None — а это ровно тот случай, ради которого
    сверка и нужна («Дмитрий» в карточке, @Anna_… в нике)."""
    for token in _tokens(raw):
        for form in (token, _norm(token)):
            if not form:
                continue
            g = fio._confident_gender(form) or fio._patronymic_gender(form)
            if g:
                return g
    return None
